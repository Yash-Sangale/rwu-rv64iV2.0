.section .data
.align 3

one:        .double 1.0
two:        .double 2.0
four:       .double 4.0
neg_one:    .double -1.0

store0:     .dword 0
store1:     .dword 0

.section .text
.global _start

_start:

# ==========================================================
# Load operands
# ==========================================================

    la      x1, one
    fld     f0, 0(x1)

    la      x2, two
    fld     f1, 0(x2)

    la      x3, four
    fld     f2, 0(x3)

    la      x4, neg_one
    fld     f3, 0(x4)

# ==========================================================
# Arithmetic
# ==========================================================

    fadd.d  f10, f0, f1      # 3.0
    fsub.d  f11, f2, f1      # 2.0
    fmul.d  f12, f1, f1      # 4.0
    fdiv.d  f13, f2, f1      # 2.0
    fsqrt.d f14, f2          # 2.0

# ==========================================================
# Compare
# ==========================================================

    feq.d   x20, f10, f10    # 1

    flt.d   x21, f0, f1      # 1

    fle.d   x22, f1, f1      # 1

# ==========================================================
# Sign Injection
# ==========================================================

    fsgnj.d  f15, f0, f3     # -1.0

    fsgnjn.d f16, f0, f3     # +1.0

    fsgnjx.d f17, f0, f3     # -1.0

# ==========================================================
# Min / Max
# ==========================================================

    fmin.d  f18, f3, f1      # -1.0

    fmax.d  f19, f3, f1      # +2.0

# ==========================================================
# FP -> INT
# ==========================================================

    fmv.x.d x23, f10

# ==========================================================
# INT -> FP
# ==========================================================

    li      x24, 4

    fcvt.d.l f20, x24

# ==========================================================
# FP -> INT conversion
# ==========================================================

    fcvt.l.d x25, f20

# ==========================================================
# FCLASS
# ==========================================================

    fclass.d x26, f0

# ==========================================================
# Store / Reload
# ==========================================================

    la      x5, store0

    fsd     f10, 0(x5)

    fld     f21, 0(x5)

    la      x6, store1

    fsd     f20, 0(x6)

    fld     f22, 0(x6)

# ==========================================================
# Done
# ==========================================================

done:
    j done