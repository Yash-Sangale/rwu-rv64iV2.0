.section .text
.global _start

_start:

    # -------------------------------------------------------
    # Basic constants
    # -------------------------------------------------------

    li x1, 100
    li x2, 25

    add x3, x1, x2          # 125
    sub x4, x1, x2          # 75

    and x5, x1, x2          # 0
    or  x6, x1, x2          # 125
    xor x7, x1, x2          # 125

    # -------------------------------------------------------
    # Shift tests
    # -------------------------------------------------------

    li x8, 1

    sll x9,  x8, x2         # 1 << 25

    li x10, -64

    sra x11, x10, x8        # -32

    li x12, 64

    srl x13, x12, x8        # 32

    # -------------------------------------------------------
    # Compare tests
    # -------------------------------------------------------

    slt  x14, x2, x1        # 1
    slt  x15, x1, x2        # 0

    sltu x16, x2, x1        # 1
    sltu x17, x1, x2        # 0

    # -------------------------------------------------------
    # Load Store
    # -------------------------------------------------------

    lui x18, %hi(test_mem)
    addi x18, x18, %lo(test_mem)

    sd x3, 0(x18)

    ld x19, 0(x18)

    # -------------------------------------------------------
    # Branch
    # -------------------------------------------------------

    beq x19, x3, beq_pass

fail_loop:
    j fail_loop

beq_pass:

    bne x19, x4, bne_pass

    j fail_loop

bne_pass:

    # -------------------------------------------------------
    # Dependency chain
    # -------------------------------------------------------

    add x20, x19, x4        # 125 + 75 = 200
    add x21, x20, x2        # 225
    add x22, x21, x8        # 226

done:
    j done

.section .bss
.align 3
test_mem:
    .dword 0